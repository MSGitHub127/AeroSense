"""Google Gemini LLM provider implementation utilizing the official google-genai SDK."""
from __future__ import annotations

import logging

from app.exceptions import RecommendationGenerationError
from app.llm.provider import LLMProvider

logger = logging.getLogger(__name__)


class GeminiProvider(LLMProvider):
    """Production LLM provider integrating Google Gemini for atmospheric advice and vision analysis."""

    def __init__(self, api_key: str, model: str = "gemini-2.5-flash") -> None:
        """Initialize the Gemini client.

        Args:
            api_key: Google Gemini API Key.
            model: Target Gemini model identifier.
        """
        self.api_key = api_key
        self.model = model
        try:
            from google import genai

            self.client = genai.Client(api_key=api_key)
        except Exception as exc:
            logger.warning("Failed to initialize Google GenAI client: %s. Using fallback mode.", exc)
            self.client = None

    def generate_air_consultation(
        self,
        question: str,
        household_context: str,
        system_instruction: str | None = None,
    ) -> str:
        """Generate conversational advice grounded in household air data using Gemini.

        Args:
            question: Inbound family query.
            household_context: Contextual air quality dossier summary.
            system_instruction: Guiding prompt directives.

        Returns:
            str: Thoughtful, scientifically grounded response.
        """
        if not self.client:
            raise RecommendationGenerationError("Gemini client is not initialized.")

        default_sys = (
            "You are AeroSense, an empathetic, scientifically rigorous urban air quality assistant. "
            "You advise families navigating severe winter smog, thermal inversions, and particulate spikes. "
            "Always emphasize practical harm reduction, timing shifts, indoor filtration, and clearly explain "
            "the direct impact of choices (PM2.5 lung exposure avoided, avoided health risks)."
        )
        sys_prompt = system_instruction or default_sys

        full_prompt = (
            f"Household Air Quality Context:\n{household_context}\n\n"
            f"Family Inquiry: {question}\n\n"
            "Provide a clear, actionable, and compassionate answer."
        )

        try:
            from google.genai import types

            response = self.client.models.generate_content(
                model=self.model,
                contents=full_prompt,
                config=types.GenerateContentConfig(
                    system_instruction=sys_prompt,
                    temperature=0.3,
                    max_output_tokens=800,
                ),
            )
            return response.text or "No response generated by Gemini."
        except Exception as exc:
            logger.error("Gemini API consultation error: %s", exc)
            raise RecommendationGenerationError(f"Gemini API failure: {exc}") from exc

    def analyze_smog_image(
        self,
        image_bytes: bytes,
        mime_type: str,
        prompt: str,
    ) -> str:
        """Analyze outdoor visibility or filter condition using Gemini Multimodal Vision.

        Args:
            image_bytes: Image binary data.
            mime_type: MIME type (e.g., image/jpeg).
            prompt: Visual inspection query.

        Returns:
            str: Gemini visual analysis report.
        """
        if not self.client:
            raise RecommendationGenerationError("Gemini client is not initialized.")

        try:
            from google.genai import types

            image_part = types.Part.from_bytes(
                data=image_bytes,
                mime_type=mime_type,
            )
            response = self.client.models.generate_content(
                model=self.model,
                contents=[image_part, prompt],
                config=types.GenerateContentConfig(
                    temperature=0.2,
                    max_output_tokens=600,
                ),
            )
            return response.text or "Unable to assess image content."
        except Exception as exc:
            logger.error("Gemini Multimodal analysis error: %s", exc)
            raise RecommendationGenerationError(f"Gemini vision error: {exc}") from exc
